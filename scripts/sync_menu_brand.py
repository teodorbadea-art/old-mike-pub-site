"""Sync canonical Old Mike tokens and public business facts to the existing menu checkout.
No network, deploy or DB writes. --check refuses drift instead of changing files.
"""
from pathlib import Path
import argparse,json,shutil
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('menu_checkout',type=Path);p.add_argument('--check',action='store_true');a=p.parse_args();dest=a.menu_checkout.resolve()
assert (dest/'app.js').is_file() and (dest/'vercel.json').is_file(),'Expected existing Meniu Electronic checkout'
s=json.loads((ROOT/'data/site.json').read_text())
facts={k:s[k] for k in ['name','phone','phone_display','email','address','hours_display','menu_url','club_url']}
facts['operator']=' · '.join(s[k] for k in ['operator_name','operator_cui','operator_trade_registry']);facts['logo']='/assets/oldmike-logo.png'
facts['website']='https://garden.oldmike.ro/';facts['restaurantSlug']='old-mike';facts['locationCode']='loc-oldmike-matei'
files={'oldmike-shell.js':(ROOT/'assets/oldmike-shell.js').read_bytes(),'assets/oldmike-design.css':(ROOT/'assets/oldmike-design.css').read_bytes(),'data/oldmike-brand.js':('/* Generated by Old Mike site scripts/sync_menu_brand.py; public facts only. */\n(function(root){const data='+json.dumps(facts,ensure_ascii=False,separators=(',',':'))+';if(typeof module!=="undefined"&&module.exports)module.exports=data;else root.OldMikeBrand=data;})(typeof window!=="undefined"?window:globalThis);\n').encode()}
for name in ['manrope-ro-v1.woff','OFL-Manrope.txt','cormorant-garamond-regular-ro.woff','cormorant-garamond-italic-ro.woff','OFL-Cormorant.txt']:
 files['assets/fonts/'+name]=(ROOT/'assets/fonts'/name).read_bytes()
files['assets/oldmike-logo.png']=(ROOT/'assets/brand/oldmike-logo.png').read_bytes()
for name,data in files.items():
 target=dest/name
 if a.check:assert target.is_file() and target.read_bytes()==data,'Brand drift: '+name
 else:target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
print('PASS' if a.check else 'SYNCED',len(files),'brand assets; canonical source: Old Mike site; no runtime cross-domain dependency')
